#!/usr/bin/env python3
"""Generate Homebrew and Scoop definitions from verified release metadata.

Writes files only; commits and publication are intentionally separate steps.
All six release archives must have unique SHA-256 entries before anything is
written. The publisher must separately verify the downloaded archive bytes.
"""

import argparse
import json
from pathlib import Path
import re


def generate(version, checksums, output):
    version = version.removeprefix("v")
    if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", version):
        raise ValueError("expected a stable MAJOR.MINOR.PATCH version")
    # Historical archives keep their original license; MIT starts at v1.2.1.
    mit_licensed = tuple(map(int, version.split("."))) >= (1, 2, 1)
    hashes = {}
    for line in checksums.read_text().splitlines():
        fields = line.split()
        if len(fields) != 2 or not re.fullmatch(r"[a-fA-F0-9]{64}", fields[0]):
            raise ValueError("invalid SHA-256 manifest entry")
        digest, name = fields
        if name in hashes:
            raise ValueError("duplicate checksum filename")
        hashes[name] = digest.lower()

    def archive(os_name, arch):
        extension = "zip" if os_name == "windows" else "tar.gz"
        return f"killport_{version}_{os_name}_{arch}.{extension}"

    for os_name in ("darwin", "linux", "windows"):
        for arch in ("amd64", "arm64"):
            if archive(os_name, arch) not in hashes:
                raise ValueError(f"missing checksum for {archive(os_name, arch)}")

    base = f"https://github.com/paarths-collab/killport/releases/download/v{version}"
    description = "Inspect and free local ports with JSON output and identity-bound plans"
    lines = [
        "# Generated by scripts/package-manifests.py. Publish using local Anonymous commits.",
        "class Killport < Formula",
        f'  desc "{description}"',
        '  homepage "https://github.com/paarths-collab/killport"',
        f'  version "{version}"',
    ]
    if mit_licensed:
        lines.append('  license "MIT"')
    for brew_os, os_name in (("macos", "darwin"), ("linux", "linux")):
        lines += ["", f"  on_{brew_os} do"]
        for cpu, arch in (("intel", "amd64"), ("arm", "arm64")):
            name = archive(os_name, arch)
            lines += [
                f"    if Hardware::CPU.{cpu}? && Hardware::CPU.is_64_bit?",
                f'      url "{base}/{name}"',
                f'      sha256 "{hashes[name]}"',
                "    end",
            ]
        lines += ["  end"]
    lines += [
        "", "  def install", '    bin.install "killport"', "  end", "",
        "  test do", '    assert_match version.to_s, shell_output("#{bin}/killport --version")',
        "  end", "end", "",
    ]
    scoop = {
        "version": version,
        "architecture": {
            cpu: {
                "url": f"{base}/{archive('windows', arch)}",
                "bin": ["killport.exe"],
                "hash": hashes[archive("windows", arch)],
            }
            for cpu, arch in (("64bit", "amd64"), ("arm64", "arm64"))
        },
        "homepage": "https://github.com/paarths-collab/killport",
        "description": description,
    }
    if mit_licensed:
        scoop["license"] = "MIT"
    (output / "Formula").mkdir(parents=True, exist_ok=True)
    (output / "Formula" / "killport.rb").write_text("\n".join(lines))
    (output / "killport.json").write_text(json.dumps(scoop, indent=4) + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", required=True)
    parser.add_argument("--checksums", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    generate(args.version, args.checksums, args.output)
